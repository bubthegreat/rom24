"""Emit generated content modules. All emitters return python source text."""
import pprint

HEADER = "# GENERATED by tools/kbk_import — do not hand-edit.\n"

# constants the engine needs at runtime (loader math + level bounds)
RUNTIME_CONSTANTS = ["MAX_LEVEL", "LEVEL_HERO", "LEVEL_IMMORTAL", "WEIGHT_STANDARD",
                     "AC_PER_ONE_PERCENT_DECREASE_DAMAGE", "MAX_STATS"]


def _fmt(name, obj):
    return f"{name} = {pprint.pformat(obj, width=100, sort_dicts=False)}\n"


def emit_constants(defines):
    from tools.kbk_import.resolve import Resolver
    r = Resolver(defines)
    body = "".join(f"{n} = {r.num(n)}\n" for n in RUNTIME_CONSTANTS if n in defines)
    return HEADER + body


def emit_classes(entries, r):
    classes, order = {}, []
    for e in entries:
        name = r.value(e[0])
        order.append(name)
        classes[name] = {
            "name": name,
            "who_name": r.value(e[1]),
            "align": r.num(e[2]),
            "xpadd": r.num(e[3]),
            "weapon": r.num(e[4]),
            "guild_rooms": [r.num(v) for v in e[5]],
            "skill_adept": r.num(e[6]),
            "thac0_00": r.num(e[7]),
            "thac0_32": r.num(e[8]),
            "hp_min": r.num(e[9]),
            "hp_max": r.num(e[10]),
            "f_mana": r.value(e[11]),
            "base_group": r.value(e[12]),
            "default_group": r.value(e[13]),
            "ctype": r.num(e[14]),
        }
    return HEADER + _fmt("CLASSES", classes) + _fmt("CLASS_ORDER", order), order


def _per_class(values, r, order):
    return {cls: r.num(values[i]) if i < len(values) else 0 for i, cls in enumerate(order)}


def emit_skills(entries, r, class_order):
    skills = {}
    for e in entries:
        name = r.value(e[0])
        if not name or name == "reserved":
            continue
        if name in skills:
            continue  # duplicate names: C skill_lookup returns the first match
        skills[name] = {
            "name": name,
            "skill_level": _per_class(e[1], r, class_order),
            "rating": _per_class(e[2], r, class_order),
            "spell_fun": r.spell_name(e[3]),
            "target": r.num(e[4]),
            "minimum_position": r.num(e[5]),
            "pgsn": r.gsn_name(e[6]),
            "slot": r.slot(e[7]),
            "min_mana": r.num(e[8]),
            "beats": r.num(e[9]),
            "noun_damage": r.value(e[10]),
            "msg_off": r.value(e[11]),
            "msg_obj": r.value(e[12]) if len(e) > 12 else "",
            "ctype": r.num(e[13]) if len(e) > 13 else 0,
        }
    return HEADER + _fmt("SKILLS", skills)


def emit_groups(entries, r, class_order):
    groups = {}
    for e in entries:
        name = r.value(e[0])
        if not name or name == "reserved":
            continue
        groups[name] = {
            "name": name,
            "rating": _per_class(e[1], r, class_order),
            "spells": [r.value(s) for s in e[2] if r.value(s)],
        }
    return HEADER + _fmt("GROUPS", groups)


def emit_races(race_entries, pc_entries, r, class_order):
    races = {}
    for e in race_entries:
        # Skip NULL terminator entries
        if not e or str(e[0]) == "NULL":
            continue
        name = r.value(e[0])
        races[name] = {"name": name, "pc_race": r.value(e[1]) if len(e) > 1 else False,
                       "act": r.num(e[2]) if len(e) > 2 else 0, "aff": r.num(e[3]) if len(e) > 3 else 0,
                       "off": r.num(e[4]) if len(e) > 4 else 0,
                       "imm": r.num(e[5]) if len(e) > 5 else 0, "res": r.num(e[6]) if len(e) > 6 else 0,
                       "vuln": r.num(e[7]) if len(e) > 7 else 0,
                       "form": r.num(e[8]) if len(e) > 8 else 0, "parts": r.num(e[9]) if len(e) > 9 else 0}
    pc_races = {}
    for e in pc_entries:
        name = r.value(e[0])
        if name.startswith("null"):
            continue
        pc_races[name] = {
            "name": name,
            "who_name": r.value(e[1]).strip() if len(e) > 1 else "",
            "align": r.num(e[2]) if len(e) > 2 else 0,
            "xpadd": r.num(e[3]) if len(e) > 3 else 0,
            "skills": [r.value(s) for s in (e[4] if len(e) > 4 else []) if r.value(s)],
            "classes": {cls: bool(r.num(e[5][i])) if len(e) > 5 and i < len(e[5]) else False
                        for i, cls in enumerate(class_order)},
            "stats": [r.num(v) for v in (e[6] if len(e) > 6 else [])] if len(e) > 6 else [],
            "max_stats": [r.num(v) for v in (e[7] if len(e) > 7 else [])] if len(e) > 7 else [],
            "size": r.num(e[8]) if len(e) > 8 else 0,
            "set_race": r.value(e[9]) if len(e) > 9 else False,
        }
    return HEADER + _fmt("RACES", races) + _fmt("PC_RACES", pc_races)


def emit_materials(text: str) -> str:
    lines = iter(text.splitlines())
    for line in lines:
        if line.split() and line.split()[0] == "MATS":
            break
    materials = {}
    for line in lines:
        line = line.strip()
        if not line or "~" not in line:
            continue
        name, rest = line.split("~", 1)
        name = name.strip()
        nums = [int(x) for x in rest.split()[:5]]
        materials[name] = {"name": name,
                           **dict(zip(("prot_pierce", "prot_bash", "prot_slash",
                                       "prot_magic", "relative_weight"), nums))}
    return HEADER + _fmt("MATERIALS", materials)


def emit_aux(tables: dict, r) -> str:
    """Emit ATTACKS, LIQUIDS, STR/INT/WIS/DEX/CON_APP, WEAPONS from parsed C tables.

    Field-mapping notes (C struct → Python namedtuple, verified against merc.h and const.py):
      attack_type : name, noun, damage, modifier(C-only)  →  name, noun, damage
      liq_type    : liq_name, liq_color, liq_affect[5]   →  name, color, proof, full, thirst, food, ssize
      str_app_type: tohit, todam, carry, wield (C == Python, 4 fields)
      int_app_type: learn  (1 field each)
      wis_app_type: practice  (1 field each)
      dex_app_type: C struct has defensive,carry,tohit,armor (4) but Python namedtuple has only defensive (1)
      con_app_type: hitp, shock  (C == Python, 2 fields)
      weapon_type : name, vnum, type, gsn(ptr→skill name)  →  name, vnum, type, gsn

    Attack table keying: entry 0 keyed "" (stock ROM24 convention) even though KBK names it "none".
    App tables: keyed by int index; values are plain lists matching Python namedtuple field count,
    so read_tables can call tupletype._make(v) directly.
    """
    parts = [HEADER]

    if "attack_table" in tables:
        attacks = {}
        for i, e in enumerate(tables["attack_table"]):
            # Skip genuinely empty entries (shouldn't happen, but defensive)
            if not e or str(e[0]).strip() == "NULL":
                continue
            name = r.value(e[0])
            # Entry 0 keyed "" per stock ROM24 convention; all others keyed by name
            key = "" if i == 0 else name
            attacks[key] = {
                "name": name,
                "noun": r.value(e[1]),
                "damage": r.num(e[2]),
                # e[3] is KBK's modifier field — not in attack_type namedtuple, omitted
            }
        parts.append(_fmt("ATTACKS", attacks))

    if "liq_table" in tables:
        # C struct: liq_name, liq_color, liq_affect[5] = {proof, full, thirst, food, ssize}
        # Python liq_type: name, color, proof, full, thirst, food, ssize
        liquids = {}
        for e in tables["liq_table"]:
            if not e or str(e[0]).strip() == "NULL":
                continue
            name = r.value(e[0])
            affect = e[2]   # nested list from {proof, full, thirst, food, ssize}
            liquids[name] = {
                "name": name,
                "color": r.value(e[1]),
                "proof": r.num(affect[0]),
                "full": r.num(affect[1]),
                "thirst": r.num(affect[2]),
                "food": r.num(affect[3]),
                "ssize": r.num(affect[4]),
            }
        parts.append(_fmt("LIQUIDS", liquids))

    # Attribute-application tables: dict[int, list] so read_tables can call tupletype._make(v).
    # nfields = Python namedtuple field count (may be less than C struct fields; take only
    # the first nfields values from each C entry in struct-declaration order).
    APP_SPECS = [
        ("str_app", "STR_APP", 4),   # str_app_type: tohit, todam, carry, wield
        ("int_app", "INT_APP", 1),   # int_app_type: learn
        ("wis_app", "WIS_APP", 1),   # wis_app_type: practice
        ("dex_app", "DEX_APP", 1),   # dex_app_type: defensive (C struct has 4 but namedtuple has 1)
        ("con_app", "CON_APP", 2),   # con_app_type: hitp, shock
    ]
    for table_key, var_name, nfields in APP_SPECS:
        if table_key in tables:
            app = {i: [r.num(v) for v in e[:nfields]]
                   for i, e in enumerate(tables[table_key])}
            parts.append(_fmt(var_name, app))

    if "weapon_table" in tables:
        # C struct: name, vnum, type, gsn(sh_int*) — gsn ptr &gsn_xxx → skill name "xxx"
        # Python weapon_type: name, vnum, type, gsn
        weapons = {}
        for e in tables["weapon_table"]:
            if not e or str(e[0]).strip() == "NULL":
                continue
            name = r.value(e[0])
            weapons[name] = {
                "name": name,
                "vnum": r.num(e[1]),
                "type": r.num(e[2]),
                "gsn": r.gsn_name(e[3]),   # "&gsn_sword" → "sword"
            }
        parts.append(_fmt("WEAPONS", weapons))

    return "".join(parts)


def _str(token):
    return token[1] if isinstance(token, tuple) and token[0] == "str" else str(token)


def emit_titles(entries, class_order):
    titles = {}
    for i, cls in enumerate(class_order):
        if i >= len(entries):
            break
        titles[cls] = [[_str(pair[0]), _str(pair[1])] for pair in entries[i]]
    return HEADER + _fmt("TITLES", titles)
